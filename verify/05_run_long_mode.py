"""Run the dsos-x86_64.img long-mode kernel directly on unicorn in 64-bit mode.

Stage 2 is generated by gen_boot.py; we locate the `jmp far 0x18:<lm64>` target,
start execution there, and emulate COM1 (0x3F8 data / 0x3FD line status).
RDTSC is synthesized so the 1e9-cycle busy-wait does not take forever.
"""
import os, pathlib, sys

REPO = pathlib.Path(__file__).resolve().parents[1]
OUTDIR = pathlib.Path(os.environ.get("VERIFY_OUT", str(REPO / "_verify_out")))
OUTDIR.mkdir(parents=True, exist_ok=True)
import importlib.util, io, struct, sys
from unicorn import *
from unicorn.x86_const import *

BASE = str(REPO)
GEN = os.path.join(BASE, "dsos", "images", "x86_64", "gen_boot.py")

spec = importlib.util.spec_from_file_location("gen_boot", GEN)
gb = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gb)

st2 = gb.stage2()
print(f"stage2: {len(st2)} bytes, limit {gb.LOAD_SECTORS*512}")

# find `jmp far` into 64-bit: ea <u32 target> <u16 0x18>
lm_entry = None
for i in range(len(st2) - 7):
    if st2[i] == 0xEA and st2[i + 5:i + 7] == b"\x18\x00":
        target = struct.unpack_from("<I", st2, i + 1)[0]
        lm_entry = target
        print(f"  far jmp @stage2+{i:#x} -> {target:#x} (selector 0x18)")
if lm_entry is None:
    print("FATAL: 64-bit entry not found")
    sys.exit(1)

uc = Uc(UC_ARCH_X86, UC_MODE_64)
uc.mem_map(0, 0x200000)
uc.mem_write(gb.STAGE2_ADDR, st2)

serial = bytearray()
stats = {"out": 0, "in": 0, "rdtsc": 0, "ports": {}}
tsc = {"v": 1_000_000_000}


def on_out(uc, *args):
    try:
        port, size, value = args[0], args[1], args[2]
    except Exception:
        port = uc.reg_read(UC_X86_REG_DX)
        value = uc.reg_read(UC_X86_REG_AL)
    stats["out"] += 1
    stats["ports"][port] = stats["ports"].get(port, 0) + 1
    if port == 0x3F8:
        serial.append(value & 0xFF)
        if len(serial) % 64 == 0 and b"tick: 5\r\n" in bytes(serial):
            uc.emu_stop()


def on_in(uc, *args):
    port = args[0] if args else (uc.reg_read(UC_X86_REG_DX) & 0xFFFF)
    stats["in"] += 1
    stats["ports"][port] = stats["ports"].get(port, 0) + 1
    # 0x3FD = LSR: bit5 = transmit holding register empty -> always ready
    return 0x20 if port == 0x3FD else 0x00


def make_rdtsc_hook(addr):
    # hook_code fires before the instruction at `addr`; synthesize TSC and skip it
    def hook(uc, address, size, ud):
        stats["rdtsc"] += 1
        tsc["v"] += 500_000_000  # 1e9-cycle wait finishes in 2 readings
        uc.reg_write(UC_X86_REG_EAX, tsc["v"] & 0xFFFFFFFF)
        uc.reg_write(UC_X86_REG_EDX, (tsc["v"] >> 32) & 0xFFFFFFFF)
        uc.reg_write(UC_X86_REG_RIP, address + 2)
    return hook


uc.hook_add(UC_HOOK_INSN, on_out, None, 1, 0, UC_X86_INS_OUT)
uc.hook_add(UC_HOOK_INSN, on_in, None, 1, 0, UC_X86_INS_IN)

# patch every `0f 31` (rdtsc) in the code region
code_end = gb.GDT_OFF
rdtsc_sites = [i for i in range(code_end - 1) if st2[i] == 0x0F and st2[i + 1] == 0x31]
print(f"  rdtsc sites: {[hex(gb.STAGE2_ADDR + s) for s in rdtsc_sites]}")
for s in rdtsc_sites:
    uc.hook_add(UC_HOOK_CODE, make_rdtsc_hook(gb.STAGE2_ADDR + s),
                begin=gb.STAGE2_ADDR + s, end=gb.STAGE2_ADDR + s)

for reg, val in ((UC_X86_REG_DS, 0x10), (UC_X86_REG_ES, 0x10), (UC_X86_REG_SS, 0x10),
                 (UC_X86_REG_RSP, 0x70000)):
    try:
        uc.reg_write(reg, val)
    except Exception as e:
        print(f"  warn: cannot set reg {reg}: {e}")

# the long-mode prologue loads DS/ES/SS = 0x10, which hardware validates against the GDT
# that stage2 built at STAGE2_ADDR+GDT_OFF (we skipped lgdt, so install it by hand)
gdt_ready = False
try:
    uc.reg_write(UC_X86_REG_GDTR, (0, gb.STAGE2_ADDR + gb.GDT_OFF, 5 * 8 - 1, 0))
    gdt_ready = True
    print(f"  GDTR installed: base={gb.STAGE2_ADDR+gb.GDT_OFF:#x} limit={5*8-1}")
except Exception as e:
    print(f"  warn: cannot set GDTR: {e}")

err = None
try:
    uc.emu_start(lm_entry, 0, count=20_000_000)
except UcError as e:
    err = e

text = bytes(serial).decode("latin-1")
print(f"\nstarted at {lm_entry:#x}, stopped after emulation")
print(f"  error: {err}")
print(f"  out calls {stats['out']}, in calls {stats['in']}, rdtsc calls {stats['rdtsc']}")
print(f"  ports: { {hex(k): v for k, v in sorted(stats['ports'].items())} }")
print(f"  serial ({len(serial)} bytes): {text!r}")
print(f"  FINAL RIP: {uc.reg_read(UC_X86_REG_RIP):#x}")

has_alive = "DsOS alive" in text
ticks = [l for l in text.replace("\r", "").split("\n") if l.startswith("tick: ")]
print(f"\n  'DsOS alive' present: {has_alive}")
print(f"  tick lines: {ticks[:6]}")
ok = has_alive and len(ticks) >= 1
print(f"  RESULT: {'PASS' if ok else 'FAIL'}")

io.open(str(OUTDIR / "_emu64_result.txt"), "w", encoding="utf-8").write(
    f"lm_entry={lm_entry:#x}\nserial={text!r}\nticks={ticks}\nresult={'PASS' if ok else 'FAIL'}\n")
